#!/usr/bin/env python3
"""Генерирует lib/theme/tokens.g.dart из design/tokens.json.

Источник истины — design/tokens.json (его собирает design/build_tokens.py).
Запуск из корня репозитория или из flutter/: python3 flutter/tool/generate_tokens.py
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
TOKENS = ROOT / 'design' / 'tokens.json'
OUT = ROOT / 'flutter' / 'lib' / 'theme' / 'tokens.g.dart'

tokens = json.loads(TOKENS.read_text(encoding='utf-8'))


def lookup(path):
    node = tokens
    for part in path.split('.'):
        node = node[part]
    return node


def resolve(value):
    """Раскрывает ссылки вида {primitive.ink.100}."""
    while isinstance(value, str) and value.startswith('{') and value.endswith('}'):
        value = lookup(value[1:-1])['$value']
    return value


def color(value):
    """#RRGGBB или #RRGGBBAA → 0xAARRGGBB."""
    hex_ = resolve(value).lstrip('#').upper()
    if len(hex_) == 6:
        hex_ += 'FF'
    return f'Color(0x{hex_[6:8]}{hex_[:6]})'


def px(value):
    return float(re.sub(r'px$', '', resolve(value)))


def camel(name):
    head, *rest = re.split(r'[-_]', name)
    return head + ''.join(p[:1].upper() + p[1:] for p in rest)


def num(v):
    return repr(float(v))


lines = [
    '// GENERATED by tool/generate_tokens.py from design/tokens.json. Do not edit by hand.',
    '// ignore_for_file: public_member_api_docs',
    '',
    "import 'dart:ui';",
    '',
    '/// Смысловые цвета одной темы (`color.light` / `color.dark`).',
    'class ModusPalette {',
]

light = tokens['color']['light']
names = [k for k in light if k != 'status' and not k.startswith('$')]
lines += [f'  final Color {camel(n)};' for n in names]
lines += ['  final Map<String, StatusColor> status;', '']
lines.append('  const ModusPalette({')
lines += [f'    required this.{camel(n)},' for n in names]
lines += ['    required this.status,', '  });', '}', '']
lines += [
    '/// Цвета бейджа статуса: текст и подложка.',
    'class StatusColor {',
    '  final Color fg;',
    '  final Color bg;',
    '  const StatusColor(this.fg, this.bg);',
    '}',
    '',
]


def palette(theme):
    node = tokens['color'][theme]
    out = [f'const {theme}Palette = ModusPalette(']
    for n in names:
        out.append(f'  {camel(n)}: {color(node[n]["$value"])},')
    out.append('  status: {')
    for code, pair in node['status'].items():
        if code.startswith('$'):
            continue
        out.append(f"    '{code}': StatusColor({color(pair['fg']['$value'])}, {color(pair['bg']['$value'])}),")
    out += ['  },', ');', '']
    return out


lines += palette('light') + palette('dark')

lines.append('/// Радиусы (`radius.*`), px.')
lines.append('abstract final class ModusRadius {')
for k, v in tokens['radius'].items():
    if not k.startswith('$'):
        lines.append(f'  static const double {camel(k)} = {num(px(v["$value"]))};')
lines += ['}', '']

lines.append('/// Отступы (`spacing.*`), px: s1 = 4 … s12 = 48.')
lines.append('abstract final class ModusSpacing {')
for k, v in tokens['spacing'].items():
    if not k.startswith('$'):
        lines.append(f'  static const double s{k} = {num(px(v["$value"]))};')
lines += ['}', '']

lines.append('/// Размеры (`size.*`), px.')
lines.append('abstract final class ModusSize {')
for k, v in tokens['size'].items():
    if not k.startswith('$'):
        lines.append(f'  static const double {camel(k)} = {num(px(v["$value"]))};')
lines += ['}', '']

lines.append('/// Шрифты (`font.family.*`): первая гарнитура из списка.')
lines.append('abstract final class ModusFont {')
for k, v in tokens['font']['family'].items():
    if not k.startswith('$'):
        lines.append(f"  static const String {camel(k)} = '{resolve(v['$value'])[0]}';")
lines += ['}', '']

lines += [
    '/// Стиль текста из `typography.*`.',
    'class TypeToken {',
    '  final String family;',
    '  final int weight;',
    '  final double size;',
    '  final double height;',
    '  final double letterSpacing;',
    '  const TypeToken(this.family, this.weight, this.size, this.height, this.letterSpacing);',
    '}',
    '',
    'abstract final class ModusType {',
]
for k, v in tokens['typography'].items():
    if k.startswith('$'):
        continue
    t = v['$value']
    family = resolve(t['fontFamily'])[0]
    weight = int(resolve(t['fontWeight']))
    size = px(t['fontSize'])
    ls = t.get('letterSpacing', '0px')
    ls = float(ls[:-2]) * size if ls.endswith('em') else px(ls)
    lines.append(
        f"  static const {camel(k)} = TypeToken('{family}', {weight}, {num(size)}, {num(t['lineHeight'])}, {round(ls, 3)});"
    )
lines += ['}', '']

lines.append('/// Тени (`shadow.*`): цвет, смещение по y, размытие.')
lines.append('abstract final class ModusShadow {')
for k, v in tokens['shadow'].items():
    if k.startswith('$'):
        continue
    s = v['$value']
    lines.append(f'  static const {camel(k)}Color = {color(s["color"])};')
    lines.append(f'  static const double {camel(k)}OffsetY = {num(px(s["offsetY"]))};')
    lines.append(f'  static const double {camel(k)}Blur = {num(px(s["blur"]))};')
lines += ['}', '']

content = '\n'.join(lines)
if '--check' in sys.argv:
    # Для теста: файл должен совпадать с тем, что сгенерировалось бы сейчас.
    if not OUT.exists() or OUT.read_text(encoding='utf-8') != content:
        print(f'{OUT.relative_to(ROOT)} устарел: запустите python3 flutter/tool/generate_tokens.py')
        sys.exit(1)
    print('ok')
    sys.exit(0)
OUT.parent.mkdir(parents=True, exist_ok=True)
OUT.write_text(content, encoding='utf-8')
print(f'wrote {OUT.relative_to(ROOT)}')
