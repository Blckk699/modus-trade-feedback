/** Цифры и знаки точечной матрицей 5×7, как на табло. Строка — ряд сверху вниз, «1» — горящая точка. */
const GLYPHS: Record<string, string[]> = {
  '0': ['01110', '10001', '10001', '10001', '10001', '10001', '01110'],
  '1': ['00100', '01100', '00100', '00100', '00100', '00100', '01110'],
  '2': ['01110', '10001', '00001', '00010', '00100', '01000', '11111'],
  '3': ['01110', '10001', '00001', '00110', '00001', '10001', '01110'],
  '4': ['00010', '00110', '01010', '10010', '11111', '00010', '00010'],
  '5': ['11111', '10000', '11110', '00001', '00001', '10001', '01110'],
  '6': ['00110', '01000', '10000', '11110', '10001', '10001', '01110'],
  '7': ['11111', '00001', '00010', '00100', '01000', '01000', '01000'],
  '8': ['01110', '10001', '10001', '01110', '10001', '10001', '01110'],
  '9': ['01110', '10001', '10001', '01111', '00001', '00010', '01100'],
  '%': ['11000', '11001', '00010', '00100', '01000', '10011', '00011'],
  ',': ['0', '0', '0', '0', '0', '1', '1'],
  '—': ['0000', '0000', '0000', '1111', '0000', '0000', '0000'],
};

const STEP = 4;
const DOT = 3;
const GAP = 1;

/**
 * Число точечной матрицей — отсылка к табло и экранам наблюдения, с которыми работает компания.
 * Рисуется SVG в цвет текста. Настоящее значение читается из `label`, сам рисунок для диктора скрыт.
 */
export function DotNumber({ value, label, className }: { value: string; label: string; className?: string }) {
  const dots: { x: number; y: number }[] = [];
  let offset = 0;
  for (const ch of value) {
    const glyph = GLYPHS[ch];
    if (!glyph) continue;
    const width = glyph[0].length;
    glyph.forEach((row, y) => {
      for (let x = 0; x < row.length; x++) if (row[x] === '1') dots.push({ x: offset + x, y });
    });
    offset += width + GAP;
  }
  const w = Math.max(1, offset - GAP) * STEP - (STEP - DOT);
  const h = 7 * STEP - (STEP - DOT);
  return (
    <svg className={className} viewBox={`0 0 ${w} ${h}`} role="img" aria-label={label} fill="currentColor">
      {dots.map((d, i) => (
        <rect key={i} x={d.x * STEP} y={d.y * STEP} width={DOT} height={DOT} rx={0.6} />
      ))}
    </svg>
  );
}
